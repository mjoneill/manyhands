#!/usr/bin/env python3
"""#2026 — write core/emoji-names.mjs: every single-code-point RGI emoji with its Unicode name, for the picker's search.

The names come from the Unicode Character Database that ships with Python (`unicodedata`), so regenerating needs
nothing downloaded. Which code points are emoji is decided by Node's own `\\p{RGI_Emoji}` -- the same test the server
applies -- so every entry is one the server accepts. Not covered (the server still accepts them): ZWJ sequences,
flags and skin-tone variants, which have no single code-point name.

Unicode data is under the Unicode License v3 (https://www.unicode.org/license.txt), which permits redistribution.

Usage: python3 scripts/gen-emoji-names.py   (from the repo root; needs `node` on PATH)
"""
import json, pathlib, subprocess, unicodedata

ROOT = pathlib.Path(__file__).resolve().parent.parent
LIST = r"""
const out = [];
for (let cp = 0x20; cp <= 0x1FFFF; cp++) {
  if (cp >= 0xD800 && cp <= 0xDFFF) continue;
  const s = String.fromCodePoint(cp);
  if (/^\p{RGI_Emoji}$/v.test(s)) out.push([cp, false]);
  else if (/^\p{RGI_Emoji}$/v.test(s + '️')) out.push([cp, true]);
}
process.stdout.write(JSON.stringify({ node: process.version, cps: out }));
"""

def main():
    got = json.loads(subprocess.run(['node', '-e', LIST], check=True, capture_output=True, text=True).stdout)
    rows, unnamed = [], []
    for cp, selector in got['cps']:
        try:
            name = unicodedata.name(chr(cp)).lower()
        except ValueError:
            unnamed.append(cp)
            continue
        rows.append([chr(cp) + ('️' if selector else ''), name])
    if unnamed:
        raise SystemExit(f'{len(unnamed)} emoji have no name in this Python\'s Unicode {unicodedata.unidata_version}: '
                         f'{[hex(c) for c in unnamed[:10]]} -- use a Python whose Unicode is at least Node\'s')
    # browse order: faces and people first, as pickers do, then nature, objects, travel, and symbols last
    blocks = [(0x1F600, 0x1F64F), (0x1F900, 0x1F9FF), (0x1FA70, 0x1FAFF), (0x1F466, 0x1F4AB), (0x1F300, 0x1F465),
              (0x1F4AC, 0x1F5FF), (0x1F680, 0x1F6FF)]
    def rank(row):
        cp = ord(row[0][0])
        for i, (lo, hi) in enumerate(blocks):
            if lo <= cp <= hi:
                return (i, cp)
        return (len(blocks), cp)
    rows.sort(key=rank)
    body = ',\n'.join('  ' + json.dumps(r, ensure_ascii=False) for r in rows)
    out = (f"// GENERATED by scripts/gen-emoji-names.py -- do not edit by hand (#2026).\n"
           f"// {len(rows)} single-code-point RGI emoji (per Node {got['node']}) named from the Unicode Character Database\n"
           f"// {unicodedata.unidata_version} (Unicode License v3, https://www.unicode.org/license.txt).\n"
           f"export const EMOJI_NAMES_UNICODE_VERSION = '{unicodedata.unidata_version}';\n"
           f"export const EMOJI_NAMES = Object.freeze([\n{body},\n]);\n")
    (ROOT / 'core' / 'emoji-names.mjs').write_text(out, encoding='utf-8')
    print(f'wrote core/emoji-names.mjs: {len(rows)} emoji, {len(out.encode())} bytes, Unicode {unicodedata.unidata_version}')

if __name__ == '__main__':
    main()
